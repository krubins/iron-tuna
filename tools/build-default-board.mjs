#!/usr/bin/env node
// Rebuilds the DEFAULT_BOARD block inside /it-league.js from the projections the
// worker already ships.
//   node tools/build-default-board.mjs
//
// WHY THERE IS A BOARD IN THE LIBRARY AT ALL. A reader who has never opened the
// draft app has no saved board, so until now every "+12% to +18% versus price"
// on the news pages stayed an abstraction for them — the one group of readers
// least able to translate it themselves. This block is the SITE'S OWN board, at
// the site's default league (12 teams, $200, full PPR), so those readers can be
// given a real number and told plainly whose league it is.
//
// It is not, and must not become, a substitute for the reader's own board. It
// carries points only — no stat lines — so it cannot be re-scored at somebody
// else's scoring, and the library never quotes it as "your league".
//
// THIS BLOCK IS THE FALLBACK, NOT THE BOARD. Read this before trusting it.
// It is built from the COMMITTED `PROJECTIONS` array. The app is served those
// projections re-blended with the DAY's odds (`blendProjections` in _worker.js,
// at VEGAS_WEIGHT = 3), so this block and the reader's cheat sheet are two
// different boards, and they diverge every time a line moves. On 2026-08-23 the
// gap was Derrick Henry at $25 here and $38 on the sheet, and Jeremiyah Love at
// $47 here and $25 on the sheet — which a story then quoted at readers as "the
// consensus sheet". This header used to claim the two were "the same
// odds-blended projections the app serves". They never were.
//
// The real board is `/api/board` (_worker.js §9d), computed off the same
// blended pool and served. /it-league.js fetches it and only falls back to this
// block when it cannot. **Never verify a price against this block.**
//
// THE RECIPE, which is the app's own (index.html `calculateMarketValues`):
//   points  = it-league.js `score()` at SCORING_DEFAULTS, run over the worker's
//             committed PROJECTIONS — no odds overlay, which is exactly why
//             this is a fallback.
//   rank    = sort by points, within position.
//   price   = the market curve at that slot, scaled to 12 x $200. Computed at
//             READ time by the library, not stored here, so a curve change needs
//             no regeneration.
// K and DEF are dropped: no editorial call is ever written about them, and they
// would be a fifth of the payload.
//
// Run after `tools/merge-projections.mjs` changes the PROJECTIONS block in
// _worker.js. `node tools/test-it-league.mjs` fails when this block and the
// worker disagree, so a forgotten run is a failed test rather than a reader
// being quoted a stale number.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = f => fs.readFileSync(path.join(ROOT, f), 'utf8');

export const KEEP = ['QB', 'RB', 'WR', 'TE'];
export const START = '  // ── generated by tools/build-default-board.mjs — do not hand-edit ──';
export const END = '  // ── end generated ──';

// The worker's PROJECTIONS, parsed the same way tools/test-you-column.mjs does.
export function projections(workerSrc) {
  const st = workerSrc.indexOf('const PROJECTIONS = [');
  const seg = workerSrc.slice(st, workerSrc.indexOf('\n];', st));
  const re = /\{ name: "([^"]+)", position: "([^"]+)", team: "([^"]+)", projectedStats: \{ ([^}]*) \}\}/g;
  const out = [];
  let m;
  while ((m = re.exec(seg))) {
    const stats = {};
    for (const kv of m[4].split(',')) {
      const q = kv.trim().match(/^(\w+): (-?[\d.]+)$/);
      if (q) stats[q[1]] = parseFloat(q[2]);
    }
    out.push({ name: m[1], position: m[2], stats });
  }
  return out;
}

// Score them with the REAL library, not a copy of it: whatever it-league.js
// says a stat line is worth is what this board is worth, by construction.
export function loadLibrary(libSrc) {
  const w = { localStorage: { getItem: () => null } };
  new Function('window', libSrc + '\n;return window.ITLeague;')(w);
  return w.ITLeague;
}

// The app re-levels each position's points to last season's top-K mean before
// printing them (normalizeToLastYear in index.html), so a board baked from raw
// scores sits on a different scale than the reader's sheet — Nacua 356.0 here
// against 330.0 on the sheet. The worker mirrors the client's rule as
// COLUMN_NORM + _colNormFactors (tools/test-worker-column.mjs pins the mirror
// against index.html); this parses that ONE mirror out of the worker source and
// applies the same rule, so the baked block, /api/board and the sheet agree.
export function normFactors(workerSrc, pool, L) {
  const m = workerSrc.match(/const COLUMN_NORM = \{([\s\S]*?)\};/);
  const norm = {};
  if (m) {
    const re = /(\w+): \{ mean: ([\d.]+), k: (\d+) \}/g;
    let q;
    while ((q = re.exec(m[1]))) norm[q[1]] = { mean: parseFloat(q[2]), k: parseInt(q[3], 10) };
  }
  const out = {};
  for (const pos of KEEP) {
    out[pos] = 1;
    if (!norm[pos]) continue;
    const arr = pool.filter(p => p.position === pos)
      .map(p => L.score(p.stats, p.position)).filter(v => v > 0).sort((a, b) => b - a);
    if (arr.length < 3) continue;
    const K = Math.max(3, Math.min(norm[pos].k, arr.length));
    const projMean = arr.slice(0, K).reduce((a, b) => a + b, 0) / K;
    if (!(projMean > 0)) continue;
    const f = norm[pos].mean / projMean;
    if (f >= 0.98 && f <= 1.02) continue;
    out[pos] = f;
  }
  return out;
}

// One player per line, "name|pos|points" — the same one-long-line convention
// front.html's generated STORIES array uses. Points carry one decimal, which is
// what the app's own snapshot rounds to.
export function boardLines(pool, L, factors) {
  const f = factors || {};
  return pool
    .filter(p => KEEP.includes(p.position))
    .map(p => {
      const raw = L.score(p.stats, p.position);
      const pts = Math.round((raw > 0 ? raw * (f[p.position] || 1) : raw) * 10) / 10;
      return { n: p.name, pos: p.position, pts };
    })
    // A player the projections do not score — a free agent with an empty line, a
    // backup under the passing-yard threshold — cannot be moved up or down
    // anything. Leaving them out is how the library keeps its promise not to
    // invent: a story naming one of them simply gets no line.
    .filter(p => p.pts > 0)
    .sort((a, b) => (a.pos === b.pos ? b.pts - a.pts : KEEP.indexOf(a.pos) - KEEP.indexOf(b.pos)))
    .map(p => `${p.n}|${p.pos}|${p.pts}`);
}

export function block(lines) {
  return [START, '  var DEFAULT_BOARD_RAW = ' + JSON.stringify(lines.join('\n')) + ';', END].join('\n');
}

// Importable for the test; only rewrites the file when run directly.
if (import.meta.url === `file://${process.argv[1]}`) {
  const lib = read('it-league.js');
  const workerSrc = read('_worker.js');
  const pool = projections(workerSrc);
  const L = loadLibrary(lib);
  const lines = boardLines(pool, L, normFactors(workerSrc, pool, L));
  const s = lib.indexOf(START), e = lib.indexOf(END);
  if (s < 0 || e < 0) {
    console.error('ABORT: could not find the DEFAULT_BOARD markers in it-league.js');
    process.exit(1);
  }
  const before = lib;
  const next = lib.slice(0, s) + block(lines) + lib.slice(e + END.length);
  fs.writeFileSync(path.join(ROOT, 'it-league.js'), next);
  const counts = KEEP.map(k => `${k} ${lines.filter(l => l.split('|')[1] === k).length}`).join(', ');
  console.log(`it-league.js: ${lines.length} players (${counts})${next === before ? ' (no change)' : ''}`);
}
